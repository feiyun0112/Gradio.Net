using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.Diagnostics;
using Microsoft.CodeAnalysis.Text;

namespace Gradio.Net.Analyzers;

/// <summary>
/// Emits <c>Gradio.Net.GradioVersion</c> from the single version source
/// (<c>eng/Versions.props</c>), so that the version the assembly declares cannot
/// disagree with the version of the package that carries it.
/// </summary>
/// <remarks>
/// The versions arrive as <c>CompilerVisibleProperty</c> values, which only the package
/// project declares; for every other project the generator emits nothing.
/// </remarks>
[Generator(LanguageNames.CSharp)]
public sealed class GradioVersionGenerator : IIncrementalGenerator
{
    private const string UpstreamVersionProperty = "build_property.GradioUpstreamVersion";
    private const string PackageVersionProperty = "build_property.GradioNetVersion";
    private const string HintName = "GradioVersion.g.cs";

    /// <inheritdoc />
    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        var versions = context.AnalyzerConfigOptionsProvider.Select(static (provider, _) => ReadVersions(provider));

        context.RegisterSourceOutput(versions, static (production, versions) =>
        {
            if (versions.Upstream.Length == 0 || versions.PackageVersion.Length == 0)
            {
                return;
            }

            production.AddSource(
                HintName,
                SourceText.From(BuildSource(versions.Upstream, versions.PackageVersion), Encoding.UTF8));
        });
    }

    private static (string Upstream, string PackageVersion) ReadVersions(AnalyzerConfigOptionsProvider provider)
    {
        var upstream = provider.GlobalOptions.TryGetValue(UpstreamVersionProperty, out var upstreamValue)
            ? upstreamValue
            : string.Empty;
        var packageVersion = provider.GlobalOptions.TryGetValue(PackageVersionProperty, out var packageValue)
            ? packageValue
            : string.Empty;

        return (upstream, packageVersion);
    }

    private static string BuildSource(string upstream, string packageVersion)
    {
        var source = new StringBuilder();
        source.AppendLine("// <auto-generated />");
        source.AppendLine("// Generated from the single version source (eng/Versions.props); do not edit.");
        source.AppendLine("#nullable enable");
        source.AppendLine();
        source.AppendLine("namespace Gradio.Net;");
        source.AppendLine();
        source.AppendLine("/// <summary>");
        source.AppendLine("/// The versions of this build, generated at compile time from the single version");
        source.AppendLine("/// source so that the declared version cannot drift from the package version.");
        source.AppendLine("/// </summary>");
        source.AppendLine("public static class GradioVersion");
        source.AppendLine("{");
        source.AppendLine("    /// <summary>The Python Gradio release this build targets.</summary>");
        source.Append("    public const string Upstream = \"").Append(upstream).AppendLine("\";");
        source.AppendLine();
        source.AppendLine("    /// <summary>The Gradio.Net package version derived from <see cref=\"Upstream\"/>.</summary>");
        source.Append("    public const string PackageVersion = \"").Append(packageVersion).AppendLine("\";");
        source.AppendLine("}");

        return source.ToString();
    }
}
