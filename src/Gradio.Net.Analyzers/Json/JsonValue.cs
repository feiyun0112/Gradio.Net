using System;
using System.Collections.Generic;
using System.Globalization;
using System.Text;

namespace Gradio.Net.Analyzers.Json;

/// <summary>
/// The subset of JSON the build-time manifests are written in, read without a dependency.
/// </summary>
/// <remarks>
/// <para>
/// The analyzer project targets netstandard2.0, which has no JSON reader in the box, and an
/// analyzer that carries a package dependency has to have that dependency resolved by the compiler
/// host as well — a build-time failure mode that is much worse than the parser it would save. The
/// manifests are generated by this repository, so the subset that has to be understood is the one
/// this repository writes: objects, arrays, strings, numbers, booleans and null.
/// </para>
/// <para>
/// A malformed document throws <see cref="FormatException"/>. Callers turn that into a diagnostic
/// naming the file, so a hand-edited manifest is reported rather than crashing the build.
/// </para>
/// </remarks>
internal sealed class JsonValue
{
    private readonly object? _value;

    private JsonValue(object? value) => _value = value;

    /// <summary>Whether this value is JSON <c>null</c>.</summary>
    internal bool IsNull => _value is null;

    /// <summary>The members of a JSON object, or <see langword="null"/> for any other kind of value.</summary>
    /// <remarks>
    /// Nullable rather than an empty collection, so that "this is not an object" and "this is an
    /// empty object" are different answers and a caller has to say which it means. It also keeps
    /// the reader free of a shared empty instance, which would be static state the package is not
    /// allowed to hold.
    /// </remarks>
    internal IReadOnlyDictionary<string, JsonValue>? Object =>
        _value as IReadOnlyDictionary<string, JsonValue>;

    /// <summary>The items of a JSON array, or <see langword="null"/> for any other kind of value.</summary>
    internal IReadOnlyList<JsonValue>? Array => _value as IReadOnlyList<JsonValue>;

    /// <summary>The value of a member of a JSON object.</summary>
    /// <param name="name">The member name.</param>
    /// <returns>The member's value, or <see langword="null"/> when this is not an object or has no such member.</returns>
    internal JsonValue? Member(string name) =>
        Object is { } members && members.TryGetValue(name, out var member) ? member : null;

    /// <summary>The value as a string, or <see langword="null"/> when it is not one.</summary>
    internal string? AsString() => _value as string;

    /// <summary>The value as a boolean, or <see langword="null"/> when it is not one.</summary>
    internal bool? AsBool() => _value is bool flag ? flag : null;

    /// <summary>The value as a number, or <see langword="null"/> when it is not one.</summary>
    /// <remarks>
    /// Every number the reader produces is a <see cref="double"/>, which is why a manifest's
    /// <c>1</c> and <c>1.0</c> are the same value here: a caller that has to write one back into a
    /// C# literal says which kind it wants rather than trusting the shape it arrived in.
    /// </remarks>
    internal double? AsNumber() => _value is double number ? number : null;

    /// <summary>Parses a document.</summary>
    /// <param name="text">The document text.</param>
    /// <returns>The value the document holds.</returns>
    /// <exception cref="FormatException">The text is not a JSON document.</exception>
    internal static JsonValue Parse(string text)
    {
        var cursor = new Cursor(text);
        cursor.SkipWhitespace();

        var value = cursor.ReadValue();
        cursor.SkipWhitespace();

        if (!cursor.AtEnd)
        {
            throw cursor.Error("trailing content after the document");
        }

        return value;
    }

    private static JsonValue Null() => new(null);

    private static JsonValue From(object value) => new(value);

    private struct Cursor
    {
        private readonly string _text;
        private int _index;

        internal Cursor(string text)
        {
            _text = text;
            _index = 0;
        }

        internal bool AtEnd => _index >= _text.Length;

        internal FormatException Error(string problem) =>
            new($"at offset {_index}: {problem}");

        internal void SkipWhitespace()
        {
            while (!AtEnd && char.IsWhiteSpace(_text[_index]))
            {
                _index++;
            }
        }

        internal JsonValue ReadValue()
        {
            if (AtEnd)
            {
                throw Error("the document ended where a value was expected");
            }

            switch (_text[_index])
            {
                case '{':
                    return ReadObject();
                case '[':
                    return ReadArray();
                case '"':
                    return From(ReadString());
                case 't':
                    Expect("true");
                    return From(true);
                case 'f':
                    Expect("false");
                    return From(false);
                case 'n':
                    Expect("null");
                    return Null();
                default:
                    return ReadNumber();
            }
        }

        private JsonValue ReadObject()
        {
            _index++; // {
            var members = new Dictionary<string, JsonValue>(StringComparer.Ordinal);

            SkipWhitespace();
            if (!AtEnd && _text[_index] == '}')
            {
                _index++;
                return From(members);
            }

            while (true)
            {
                SkipWhitespace();
                var name = ReadString();

                SkipWhitespace();
                Expect(":");

                SkipWhitespace();
                members[name] = ReadValue();

                SkipWhitespace();
                if (AtEnd)
                {
                    throw Error("the object was not closed");
                }

                if (_text[_index] == ',')
                {
                    _index++;
                    continue;
                }

                Expect("}");
                return From(members);
            }
        }

        private JsonValue ReadArray()
        {
            _index++; // [
            var items = new List<JsonValue>();

            SkipWhitespace();
            if (!AtEnd && _text[_index] == ']')
            {
                _index++;
                return From(items);
            }

            while (true)
            {
                SkipWhitespace();
                items.Add(ReadValue());

                SkipWhitespace();
                if (AtEnd)
                {
                    throw Error("the array was not closed");
                }

                if (_text[_index] == ',')
                {
                    _index++;
                    continue;
                }

                Expect("]");
                return From(items);
            }
        }

        private string ReadString()
        {
            Expect("\"");

            var text = new StringBuilder();
            while (true)
            {
                if (AtEnd)
                {
                    throw Error("the string was not closed");
                }

                var character = _text[_index++];

                if (character == '"')
                {
                    return text.ToString();
                }

                if (character != '\\')
                {
                    text.Append(character);
                    continue;
                }

                if (AtEnd)
                {
                    throw Error("the string ended inside an escape");
                }

                var escape = _text[_index++];
                switch (escape)
                {
                    case '"':
                    case '\\':
                    case '/':
                        text.Append(escape);
                        break;
                    case 'b':
                        text.Append('\b');
                        break;
                    case 'f':
                        text.Append('\f');
                        break;
                    case 'n':
                        text.Append('\n');
                        break;
                    case 'r':
                        text.Append('\r');
                        break;
                    case 't':
                        text.Append('\t');
                        break;
                    case 'u':
                        text.Append(ReadCodePoint());
                        break;
                    default:
                        throw Error($"'\\{escape}' is not an escape this reader knows");
                }
            }
        }

        private char ReadCodePoint()
        {
            if (_index + 4 > _text.Length)
            {
                throw Error("a \\u escape was cut short");
            }

            var digits = _text.Substring(_index, 4);
            _index += 4;

            return ushort.TryParse(digits, NumberStyles.HexNumber, CultureInfo.InvariantCulture, out var code)
                ? (char)code
                : throw Error($"'{digits}' is not a hexadecimal escape");
        }

        private JsonValue ReadNumber()
        {
            var start = _index;

            while (!AtEnd && (char.IsDigit(_text[_index]) || _text[_index] is '-' or '+' or '.' or 'e' or 'E'))
            {
                _index++;
            }

            var text = _text.Substring(start, _index - start);

            return double.TryParse(text, NumberStyles.Float, CultureInfo.InvariantCulture, out var number)
                ? From(number)
                : throw Error($"'{text}' is not a number");
        }

        private void Expect(string literal)
        {
            if (_index + literal.Length > _text.Length
                || string.CompareOrdinal(_text, _index, literal, 0, literal.Length) != 0)
            {
                throw Error($"'{literal}' was expected");
            }

            _index += literal.Length;
        }
    }
}
